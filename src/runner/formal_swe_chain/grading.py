"""Resolve released truncated pytest IDs against a frozen reference test list.

Raw tests and patches are unchanged. If several full IDs share
one released prefix, all of those reference IDs must pass. Missing IDs fail.
"""
from pathlib import Path
import re
import shutil

from swe_chain_evo.common import ROOT, atomic, instance, read, sha
from swe_chain_evo.grading import parse_statuses
from .command_recovery import complete_test_logs


def map_path(entry):
    return ROOT / "runs/grader-preflight" / entry["instance_id"] / "test-id-map.json"


def resolve_ids(required, reference_statuses):
    mapping = {}
    for short in required:
        if short in reference_statuses:
            mapping[short] = [short]
            continue
        # A released color-output parameter lost its escaped ANSI CSI suffix,
        # while retaining the literal \\x1b prefix. Compare this deterministic
        # representation only against the frozen reference IDs, never against
        # arbitrary names returned by a candidate's evaluation.
        escaped = sorted(name for name in reference_statuses
            if re.sub(r"(\\x1b)\[[0-?]*[ -/]*[@-~]", r"\1", name) == short)
        if escaped:
            mapping[short] = escaped
            continue
        # Released metadata was generated by a whitespace-splitting parser.
        # Restrict recovery to incomplete parametrized pytest node IDs.
        matches = sorted(name for name in reference_statuses
            if "[" in short and not short.endswith("]") and name.startswith(short)
            and len(name) > len(short) and name[len(short)].isspace())
        if not matches:
            raise ValueError("required reference test cannot be resolved: " + short)
        mapping[short] = matches
    return mapping


def logs(folder):
    files = sorted(Path(folder).glob("command-*.log"))
    return "\n".join(p.read_text() for p in files), {p.name: sha(p) for p in files}


def freeze_map(entry, oracle_folder):
    item = instance(entry)
    oracle_folder = complete_test_logs(entry, oracle_folder)
    text, hashes = logs(oracle_folder)
    statuses = parse_statuses(text)
    required = list(dict.fromkeys(item["fail_to_pass"] + item["pass_to_pass"]))
    mapping = resolve_ids(required, statuses)
    value = {"instance_id": item["instance_id"],
        "instance_sha256": sha(ROOT / "data/SWE-Chain-Evo" / entry["instance_path"]),
        "mapping": mapping, "reference_log_sha256": hashes,
        "reference_log_directory": str(oracle_folder),
        "policy": "exact ID preferred; truncated ID expands to all matching reference IDs; missing/nonpass fails",
        "normalizer_sha256": sha(Path(__file__))}
    target = map_path(entry)
    if target.exists() and read(target) != value:
        raise RuntimeError("frozen reference test IDs changed")
    atomic(target, value)
    return value


def score(mapping, statuses):
    required = list(dict.fromkeys(name for names in mapping.values() for name in names))
    missing = [n for n in required if n not in statuses]
    nonpassing = [n for n in required if statuses.get(n) != "PASS"]
    return {"reward": int(not nonpassing), "required_tests": len(required),
        "observed_required_tests": len(required) - len(missing),
        "passed_required_tests": len(required) - len(nonpassing),
        "missing_tests": missing, "nonpassing_tests": nonpassing, "test_statuses": statuses}


def normalize(entry, folder):
    folder = Path(folder)
    target = folder / "grade.json"
    saved = read(target)
    # Prediction apply failures have no test results to normalize.
    if saved.get("reason") == "prediction_or_test_patch_apply_failed":
        return saved
    frozen = read(map_path(entry))
    if frozen["normalizer_sha256"] != sha(Path(__file__)):
        raise RuntimeError("test ID normalizer changed after reference calibration")
    if frozen["instance_sha256"] != saved["identity"]["instance_sha256"]:
        raise RuntimeError("test ID map belongs to a different instance")
    raw = folder / "grade.raw.json"
    if not raw.exists():
        shutil.copy2(target, raw)
    effective = complete_test_logs(entry, folder)
    text, hashes = logs(effective)
    value = {**read(raw), **score(frozen["mapping"], parse_statuses(text)),
        "test_id_normalization": {"map": str(map_path(entry)), "map_sha256": sha(map_path(entry)),
            "normalizer_sha256": sha(Path(__file__)), "raw_grade_sha256": sha(raw), "test_log_sha256": hashes,
            "test_log_directory": str(effective)}}
    atomic(target, value)
    return value
