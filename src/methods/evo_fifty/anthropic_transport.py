"""API codec for the original Claude Code proposer, not a replacement agent.

The solver, tool execution, delegation, history and editing remain in Claude
Code. Only the message wire format crosses this bridge. Provider receipts in
Broker remain the authoritative source of tokens and cost.
"""
from __future__ import annotations

import json


def content_blocks(content):
    return [{'type': 'text', 'text': content}] if isinstance(content, str) else content or []


def ordinary(blocks):
    result = []
    for b in content_blocks(blocks):
        kind = b.get('type')
        if kind == 'text':
            result.append({'type': 'text', 'text': b['text']})
        elif kind == 'image':
            source = b['source']
            if source['type'] == 'base64':
                url = 'data:' + source['media_type'] + ';base64,' + source['data']
            elif source['type'] == 'url':
                url = source['url']
            else:
                raise ValueError('unsupported image source')
            result.append({'type': 'image_url', 'image_url': {'url': url}})
        elif kind in ('thinking', 'redacted_thinking'):
            # Anthropic signatures cannot be sent to a different provider.
            # Reasoning is regenerated by the pinned DeepSeek configuration.
            continue
        else:
            raise ValueError('unsupported Anthropic content block: ' + str(kind))
    if all(x['type'] == 'text' for x in result):
        return '\n'.join(x['text'] for x in result)
    return result


def to_chat(body):
    messages = []
    if body.get('system'):
        messages.append({'role': 'system', 'content': ordinary(body['system'])})
    for item in body['messages']:
        blocks = content_blocks(item['content'])
        if item['role'] == 'assistant':
            calls = [b for b in blocks if b['type'] == 'tool_use']
            message = {'role': 'assistant', 'content': ordinary([b for b in blocks if b['type'] != 'tool_use'])}
            if calls:
                message['tool_calls'] = [{'id': b['id'], 'type': 'function', 'function': {
                    'name': b['name'], 'arguments': json.dumps(b['input'], ensure_ascii=False)}} for b in calls]
            messages.append(message)
        else:
            pending = []
            for b in blocks:
                if b['type'] == 'tool_result':
                    if pending:
                        messages.append({'role': 'user', 'content': ordinary(pending)})
                        pending = []
                    messages.append({'role': 'tool', 'tool_call_id': b['tool_use_id'],
                                     'content': ordinary(b.get('content', ''))})
                else:
                    pending.append(b)
            if pending:
                messages.append({'role': 'user', 'content': ordinary(pending)})
    out = {'model': body['model'], 'messages': messages, 'max_tokens': body['max_tokens'], 'stream': False}
    if body.get('tools'):
        tools = []
        for tool in body['tools']:
            if tool.get('type') not in (None, 'custom'):
                raise ValueError('unsupported hosted Anthropic tool')
            tools.append({'type': 'function', 'function': {'name': tool['name'],
                          'description': tool.get('description', ''), 'parameters': tool['input_schema']}})
        out['tools'] = tools
    choice = body.get('tool_choice', {'type': 'auto'})
    if choice['type'] == 'tool':
        out['tool_choice'] = {'type': 'function', 'function': {'name': choice['name']}}
    else:
        out['tool_choice'] = {'any': 'required', 'none': 'none', 'auto': 'auto'}[choice['type']]
    if body.get('stop_sequences'):
        out['stop'] = body['stop_sequences']
    return out


def from_chat(raw):
    choice = raw['choices'][0]
    message = choice['message']
    blocks = []
    if message.get('content'):
        if not isinstance(message['content'], str):
            raise ValueError('unexpected provider assistant content')
        blocks.append({'type': 'text', 'text': message['content']})
    for call in message.get('tool_calls') or []:
        blocks.append({'type': 'tool_use', 'id': call['id'], 'name': call['function']['name'],
                       'input': json.loads(call['function']['arguments'])})
    usage = raw['usage']
    return {'id': raw['id'], 'type': 'message', 'role': 'assistant', 'model': raw['model'],
            'content': blocks, 'stop_reason': {'tool_calls': 'tool_use', 'length': 'max_tokens',
            'stop': 'end_turn'}.get(choice['finish_reason'], 'end_turn'), 'stop_sequence': None,
            'usage': {'input_tokens': usage['prompt_tokens'], 'output_tokens': usage['completion_tokens'],
                      'cache_creation_input_tokens': 0, 'cache_read_input_tokens': 0}}


def stream_message(message):
    """Emit Anthropic SSE only after the complete response and bill are saved."""
    events = []
    start = {**message, 'content': [], 'stop_reason': None,
             'usage': {**message['usage'], 'output_tokens': 0}}
    events.append(('message_start', {'type': 'message_start', 'message': start}))
    events.append(('ping', {'type': 'ping'}))
    for i, block in enumerate(message['content']):
        initial = {**block}
        if block['type'] == 'text':
            initial['text'] = ''
            delta = {'type': 'text_delta', 'text': block['text']}
        else:
            initial['input'] = {}
            delta = {'type': 'input_json_delta', 'partial_json': json.dumps(block['input'], ensure_ascii=False)}
        events.append(('content_block_start', {'type': 'content_block_start', 'index': i, 'content_block': initial}))
        events.append(('content_block_delta', {'type': 'content_block_delta', 'index': i, 'delta': delta}))
        events.append(('content_block_stop', {'type': 'content_block_stop', 'index': i}))
    events.append(('message_delta', {'type': 'message_delta', 'delta': {
        'stop_reason': message['stop_reason'], 'stop_sequence': None}, 'usage': message['usage']}))
    events.append(('message_stop', {'type': 'message_stop'}))
    return ''.join('event: ' + name + '\ndata: ' + json.dumps(value, ensure_ascii=False) + '\n\n'
                   for name, value in events).encode()
